#!/usr/bin/env python3
"""Capacity-bound schedule model for building MERCURY with development agents.

ESTIMATES ONLY — no measured data. Reads docs/mercury/development-orchestration/data/dag.json
(generated by `devorch.py dag`) and simulates list scheduling with:
  * N agent workers for agent-executable work,
  * ONE Mac/operator lane (capacity configurable) for T4/T5/ⓗ/[ROOT] work,
  * per-task review/test/integration overhead, extra overhead per worker beyond 2,
  * fixed human/calendar delays at gate issues (shadow, pilot, gate reviews).
Priority = longest remaining path, then number of downstream issues.
Assumption values are documented in 05-dependency-and-critical-path.md §4.
"""
import heapq, json, os, sys
DAG = os.path.join(os.path.dirname(__file__), "..", "..", "docs", "mercury", "development-orchestration", "data", "dag.json")

def sim(d, workers, k_agent, ovh, sec_ovh, integ, mac_cap=1, mac_frac=0.35, unc=0.0, gate_days=None, trace=None):
    base = {k: v for k, v in d["issues"].items() if not v["conditional"]}
    gate_days = gate_days or {"MERC-005": 1, "MERC-406": 1, "MERC-508": 1, "MERC-805": 1, "MERC-905": 1, "MERC-904": 5, "MERC-901": 10}
    tasks = {}
    for k, v in base.items():
        p = v["p50"] * (1 + unc); env = v["env"]; mac = v["needs_mac_or_operator"]
        pure = mac and not any(t in env for t in ("T0", "T1", "T2", "T3", "CI"))
        a = 0 if pure else p * ((1 - mac_frac) if mac else 1) * k_agent
        m = p * 0.7 if pure else (p * mac_frac * 0.8 if mac else 0)
        if a: a += ovh + (sec_ovh if v["security"] else 0) + integ * max(0, workers - 2)
        tasks[k] = (a, m)
    t, done, started, ev = 0.0, {}, set(), []
    free_a, free_m, busy = workers, mac_cap, 0.0
    while len(done) < len(base):
        for k in sorted((k for k in base if k not in started and all(done.get(x, 1e18) <= t for x in base[k]["deps"])),
                        key=lambda k: (-base[k]["longest_path_p50"], -base[k]["downstream"])):
            a, m = tasks[k]
            if a and free_a: free_a -= 1; started.add(k); busy += a; heapq.heappush(ev, (t + a, k, "a"))
            elif not a and free_m: free_m -= 1; started.add(k); heapq.heappush(ev, (t + m, k, "m"))
            else: continue
            if trace is not None: trace[k] = {"start": round(t, 1)}
        t, k, ph = heapq.heappop(ev)
        if ph == "z":          # wake-up marker for a gate delay; nothing to release
            continue
        if ph == "a":
            free_a += 1
            if tasks[k][1]: heapq.heappush(ev, (t, k, "q")); continue
        elif ph == "q":
            if free_m: free_m -= 1; heapq.heappush(ev, (t + tasks[k][1], k, "m"))
            else: heapq.heappush(ev, (t + 0.25, k, "q"))
            continue
        else:
            free_m += 1
        done[k] = t + gate_days.get(k, 0)
        if trace is not None: trace[k]["done"] = round(done[k], 1)
        if done[k] > t: heapq.heappush(ev, (done[k], "~", "z"))
    end = max(done.values())
    return round(end), round(busy / (workers * end), 2)

SCENARIOS = [  # name, workers, review+test overhead/task (days), security overhead, integration overhead per worker>2, mac lanes, mac share of mixed tasks
    ("A conservative", 2, 0.40, 0.30, 0.00, 1, 0.35),
    ("B balanced", 3, 0.45, 0.30, 0.10, 1, 0.35),
    ("C accelerated: 5 workers only", 5, 0.50, 0.35, 0.15, 1, 0.35),
    ("C' accelerated: 4 workers + macOS CI/VM offload", 4, 0.50, 0.35, 0.12, 2, 0.20),
]
CASES = [("optimistic", 0.40, 0.00), ("expected", 0.55, 0.00), ("pessimistic", 0.80, 0.25)]  # agent speed factor vs engineer-days, estimate inflation

if __name__ == "__main__":
    d = json.load(open(DAG))
    if len(sys.argv) > 1 and sys.argv[1] == "--plan":   # scenario B, expected case: per-issue start/finish (working days)
        tr = {}
        sim(d, 3, 0.55, 0.45, 0.30, 0.10, trace=tr)
        for k, v in sorted(tr.items(), key=lambda kv: kv[1]["start"]):
            print(f"{k}\t{v['start']}\t{v['done']}")
        sys.exit(0)
    print("scenario | case | elapsed working days | agent-lane utilisation")
    for name, w, o, s, i, mc, mf in SCENARIOS:
        for case, k, u in CASES:
            e, util = sim(d, w, k, o, s, i, mac_cap=mc, mac_frac=mf, unc=u)
            print(f"{name} | {case} | {e} | {util}")
