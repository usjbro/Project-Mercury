#!/usr/bin/env python3
"""Capacity-bound schedule model for building MERCURY with development agents (v2).

ESTIMATES ONLY — no measured data. Reads docs/mercury/development-orchestration/data/dag.json
(generated by `devorch.py dag`). Every number in 05-dependency-and-critical-path.md §4 is printed
by one of:
    python3 tools/devorch/schedule_model.py              # scenario table
    python3 tools/devorch/schedule_model.py --sensitivity
    python3 tools/devorch/schedule_model.py --plan        # per-issue schedule, scenario B expected

Model (v2, after review R3):
  * Two resources: N agent workers; ONE operator lane (the operator, incl. the Mac) whose effective
    speed is scaled by an availability fraction (1.0 = full-time, 0.5, 0.2 = RA-D4 pattern).
  * One priority queue per resource; priority = longest remaining path, then downstream count
    (fixes R3-01 priority inversion).
  * Each issue = optional agent part, then optional operator part, then the operator's PR review and
    merge (`pr_review` operator-days, R3-02) for issues that produce code. Dependents start only after
    the merge (conservative; stacking is shown as a sensitivity row).
  * Operator-dominant tasks (human-only identity/ruleset/App work, [ROOT] steps) carry 80 % of their
    effort on the lane; [ROOT] steps get an agent preparation + security review predecessor (R3-09).
  * G-S1 constraint: the Mac part of MERC-401 waits for MERC-302 (which records G-S1) (R3-06).
  * M9 calendar per roadmap §6 / OD-16 (R3-03): shadow 10, pilot 15 (P50) .. 30 (P90) working days.
    End-point = cutover start (MERC-906 done). The 30-day cutover watch (~22 working days) is reported
    separately and is not included.
"""
import copy, heapq, json, os, sys

DAG = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "docs", "mercury",
                   "development-orchestration", "data", "dag.json")
OPERATOR_DOMINANT = {"MERC-020", "MERC-021", "MERC-022", "MERC-023", "MERC-024", "MERC-903", "MERC-905", "MERC-906"}
NO_PR = {"MERC-001", "MERC-002", "MERC-003", "MERC-004", "MERC-005", "MERC-010", "MERC-011", "MERC-012",
         "MERC-020", "MERC-021", "MERC-022", "MERC-406", "MERC-805", "MERC-901", "MERC-903", "MERC-904",
         "MERC-905", "MERC-906"}  # evidence/decision tasks: no code PR to review
WAIT_FOR_MAC_PART = {"MERC-401": "MERC-302"}  # Mac part of 401 needs G-S1 (recorded by 302)


def build(d, k_agent, ovh, sec_ovh, integ, workers, mac_frac, unc, pr_review, gates):
    base = {k: v for k, v in d["issues"].items() if not v["conditional"]}
    T = {}
    for k, v in base.items():
        p = v["p50"] * (1 + unc)
        env, mac = v["env"], v["needs_mac_or_operator"]
        agent_env = any(t in env for t in ("T0", "T1", "T2", "T3", "CI"))
        if k in OPERATOR_DOMINANT:
            a, m = p * 0.2 * k_agent, p * 0.8
        elif mac and not agent_env:
            a, m = (0.5 + (0.3 if v["root"] else 0.0)) * k_agent * 2, p * 0.7  # agent prep (+security review if ROOT)
        elif mac:
            a, m = p * (1 - mac_frac) * k_agent, p * mac_frac * 0.8
        else:
            a, m = p * k_agent, 0.0
        if a:
            a += ovh + (sec_ovh if v["security"] else 0) + integ * max(0, workers - 2)
        r = 0.0 if k in NO_PR else pr_review
        T[k] = {"a": a, "m": m, "r": r, "gate": gates.get(k, 0.0)}
    return base, T


def sim(d, workers=3, k_agent=0.55, ovh=0.45, sec_ovh=0.30, integ=0.10, mac_frac=0.35, unc=0.0,
        pr_review=0.15, avail=1.0, gates=None, stacked=False, trace=None):
    if gates is None:
        gates = {"MERC-005": 1, "MERC-406": 1, "MERC-508": 1, "MERC-805": 1, "MERC-905": 1,
                 "MERC-901": 10, "MERC-904": 15}
    base, T = build(d, k_agent, ovh, sec_ovh, integ, workers, mac_frac, unc, pr_review, gates)
    lp = {k: v["longest_path_p50"] for k, v in base.items()}
    dn = {k: v["downstream"] for k, v in base.items()}
    prio = lambda k: (-lp[k], -dn[k], k)
    # per-issue phase: next phase in order a -> m -> r ; "avail_at" = when deps are satisfied for the next phase
    phase = {k: [p for p in ("a", "m", "r") if T[k][p] > 0] for k in base}
    released = {}          # k -> time dependents may start (stacked: at G6, before the review)
    done = {}              # k -> time every phase and the gate are complete
    ready_at = {}          # (k, phase) -> time it became runnable
    free = {"agent": workers, "op": 1}
    t, ev, busy = 0.0, [], {"agent": 0.0, "op": 0.0}
    running = set()
    lane = lambda p: "agent" if p == "a" else "op"
    dur = lambda k, p: T[k][p] / (avail if p in ("m", "r") else 1.0)

    def deps_ok(k):
        return all(x in released and released[x] <= t for x in base[k]["deps"])

    def mac_gate_ok(k):
        g = WAIT_FOR_MAC_PART.get(k)
        return g is None or (g in released and released[g] <= t)

    def finish(k, when):
        done[k] = when + T[k]["gate"]
        released.setdefault(k, done[k])   # a stacked task was released at G6 already
        if trace is not None:
            trace[k]["done"] = round(done[k], 1)
        if released[k] > t:
            heapq.heappush(ev, (released[k], "~", "~", "wake"))

    started = set()
    while len(done) < len(base):   # not `released`: a stacked task still owes its review (Codex review on PR #2)
        progressed = True
        while progressed:
            progressed = False
            for res in ("agent", "op"):
                if not free[res]:
                    continue
                cands = []
                for k in base:
                    if k in done or k in running or not phase[k]:
                        continue
                    p = phase[k][0]
                    if lane(p) != res:
                        continue
                    first = k not in started
                    if first and not deps_ok(k):
                        continue
                    if p == "m" and not mac_gate_ok(k):
                        continue
                    cands.append(k)
                for k in sorted(cands, key=prio)[:free[res]]:
                    p = phase[k][0]
                    free[res] -= 1
                    running.add(k)
                    if k not in started:
                        started.add(k)
                        if trace is not None:
                            trace[k] = {"start": round(t, 1)}
                    busy[res] += dur(k, p)
                    heapq.heappush(ev, (t + dur(k, p), k, p, "end"))
                    progressed = True
        if not ev:
            stuck = [k for k in base if k not in done]
            raise RuntimeError(f"deadlock: {stuck[:5]}")
        t, k, p, kind = heapq.heappop(ev)
        if kind == "wake":
            continue
        free[lane(p)] += 1
        running.discard(k)
        phase[k].pop(0)
        if stacked and phase[k] == ["r"]:
            # stacked PRs: dependents may start at G6 (agent done), review still consumes the lane later
            released.setdefault(k, t)
        if not phase[k]:
            finish(k, t)
    end = max(done.values())
    return round(end), round(busy["agent"] / (workers * end), 2), round(busy["op"] / end, 2)


SCENARIOS = [  # name, workers, ovh, sec_ovh, integ, mac_frac
    ("A conservative", 2, 0.40, 0.30, 0.00, 0.35),
    ("B balanced", 3, 0.45, 0.30, 0.10, 0.35),
    ("C accelerated (5 workers)", 5, 0.50, 0.35, 0.15, 0.35),
    ("C' accelerated (4 workers + macOS CI/VM offload)", 4, 0.50, 0.35, 0.12, 0.20),
]
CASES = [("optimistic", dict(k_agent=0.40, unc=0.0, pr_review=0.10, pilot=15)),
         ("expected", dict(k_agent=0.55, unc=0.0, pr_review=0.15, pilot=15)),
         ("pessimistic", dict(k_agent=0.80, unc=0.25, pr_review=0.25, pilot=30))]


def gates_for(pilot):
    return {"MERC-005": 1, "MERC-406": 1, "MERC-508": 1, "MERC-805": 1, "MERC-905": 1, "MERC-901": 10, "MERC-904": pilot}


def run(d, name, w, o, s, i, mf, case, avail=1.0, **kw):
    c = dict(case)
    pilot = c.pop("pilot")
    return sim(d, workers=w, ovh=o, sec_ovh=s, integ=i, mac_frac=mf, avail=avail, gates=gates_for(pilot), **c, **kw)


def main():
    d = json.load(open(DAG))
    args = sys.argv[1:]
    if args[:1] == ["--plan"]:
        tr = {}
        run(d, *SCENARIOS[1], CASES[1][1], trace=tr)
        print("issue\tstart\tdone")
        for k, v in sorted(tr.items(), key=lambda kv: (kv[1]["start"], kv[0])):
            print(f"{k}\t{v['start']}\t{v['done']}")
        return
    if args[:1] == ["--sensitivity"]:
        B = SCENARIOS[1]
        exp = CASES[1][1]
        rows = [
            ("B expected (operator full-time)", dict()),
            ("operator 50 % available", dict(avail=0.5)),
            ("operator 20 % available (RA-D4: 2 x 1/2 day per week)", dict(avail=0.2)),
            ("PRs stacked (dependents start at G6)", dict(stacked=True)),
            ("PR review 0.25 d each", dict(pr_review_override=0.25)),
            ("1 worker", dict(workers_override=1)),
            ("4 workers", dict(workers_override=4)),
            ("unlimited workers, no integration overhead (floor)", dict(workers_override=60, integ_override=0.0)),
        ]
        print("variation | elapsed working days | agent util | operator-lane util")
        for label, kw in rows:
            name, w, o, s, i, mf = B
            c = dict(exp)
            if "pr_review_override" in kw:
                c["pr_review"] = kw.pop("pr_review_override")
            if "workers_override" in kw:
                w = kw.pop("workers_override")
            if "integ_override" in kw:
                i = kw.pop("integ_override")
            e, ua, uo = run(d, name, w, o, s, i, mf, c, **kw)
            print(f"{label} | {e} | {ua} | {uo}")
        return
    print("scenario | case | elapsed working days to cutover start | agent util | operator-lane util")
    for sc in SCENARIOS:
        for cname, case in CASES:
            e, ua, uo = run(d, *sc, case)
            print(f"{sc[0]} | {cname} | {e} | {ua} | {uo}")


if __name__ == "__main__":
    main()
