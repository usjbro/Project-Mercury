#!/usr/bin/env python3
"""PreToolUse guard for MERCURY development *specialist* subagents (tripwire, not a security boundary).

Configured in each specialist's frontmatter (generated by tools/devorch/gen_agents.py).  Reads the
hook JSON from stdin; exits 2 (block, message on stderr) when a Bash command or file edit touches
something specialists must never touch: pushing, the GitHub CLI or API, the ledger tool or ledger
worktree, git configuration/hooks/remotes/worktrees, Claude configuration, credentials, persistence.
The real boundaries are the `main` ruleset and the development identity (08-…-security.md §4).
"""
import json, os, re, sys

BASH_DENY = [
    (r"(^|[\s;&|(`'\"/\\=])git\b[^;&|]*\bpush\b", "git push (only the orchestrator pushes, via devorch.py push)"),
    (r"\$\{?\w+\}?[^;&|]*\bpush\b|\bsend-pack\b|\bpush\s+(origin|https?:|git@|ssh:)", "git push via indirection"),
    (r"\bgit\b[^;&|]*\bupdate-index\b[^;&|]*--(skip-worktree|assume-unchanged)|core\.fsmonitor|GIT_DIR=|GIT_CONFIG", "git index/config tampering"),
    (r"(^|[\s;&|(`'\"/])gh(\s|$)", "GitHub CLI"),
    (r"(curl|wget|http|httpie|python3?\s+-c|node\s+-e)[^;&|]*(api\.github\.com|github\.com/repos|api\.linear\.app)", "direct GitHub/Linear API call"),
    (r"devorch\.py|tools/devorch/", "the devorch ledger tool"),
    (r"\bgit\b[^;&|]*\b(config|remote|worktree|update-ref|symbolic-ref|replace|filter-branch|gc|prune)\b", "git configuration/remotes/worktrees/refs"),
    (r"--git-common-dir|\.git/(hooks|config|info)|core\.hooksPath|credential\.helper|insteadOf|sshCommand", "git internals"),
    (r"\bgit\b[^;&|]*\bcredential\b", "git credentials"),
    (r"\.claude/(settings|agents)|CLAUDE\.md|\.mcp\.json", "Claude Code configuration"),
    (r"~/\.ssh|/\.ssh/|\.config/gh|\.git-credentials|\.netrc|\.claude/\.credentials|Library/Keychains|\bsecurity\s+(find|dump|export)", "credentials"),
    (r"\b(sudo|launchctl|crontab|dscl|sysadminctl|osascript)\b|Library/LaunchAgents", "privileged or persistent host change"),
    (r"mercury-devorch", "the ledger worktree"),
]
PATH_DENY = [r"/\.git(/|$)", r"/\.claude/", r"/CLAUDE\.md$", r"/tools/devorch/", r"/\.mcp\.json$", r"mercury-devorch",
             r"/\.ssh/", r"/Library/LaunchAgents/", r"/\.config/gh/", r"\.git-credentials$", r"\.netrc$"]


def block(why):
    print(f"Blocked by MERCURY development guard: {why}. Specialists may not do this; escalate in your result instead.",
          file=sys.stderr)
    sys.exit(2)


def main():
    try:
        data = json.load(sys.stdin)
    except Exception:
        block("unreadable hook input")
    tool, inp = data.get("tool_name", ""), data.get("tool_input", {}) or {}
    if tool == "Bash":
        cmd = inp.get("command", "")
        for pat, why in BASH_DENY:
            if re.search(pat, cmd):
                block(why)
    elif tool in ("Edit", "Write", "NotebookEdit", "MultiEdit"):
        path = os.path.abspath(os.path.expanduser(inp.get("file_path") or inp.get("notebook_path") or ""))
        for pat in PATH_DENY:
            if re.search(pat, path):
                block(f"writing {path}")
    sys.exit(0)


if __name__ == "__main__":
    main()
